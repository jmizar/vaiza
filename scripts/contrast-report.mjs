// Writes design/a11y-flags.md: WCAG contrast for every text/background pairing
// the designs use. FLAG ONLY: colours are design decisions and are never changed here.
// Run: npm run contrast
import { readFileSync, writeFileSync } from 'node:fs'

const t = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'))
const c = t.color

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const lum = (h) => {
  const [r, g, b] = hex(h).map((v) => {
    v /= 255
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
export const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m)
  return (x + 0.05) / (y + 0.05)
}

// [label, foreground token, background token, usage, isLargeOrBoldText, isUIComponent]
const pairs = [
  ['Primary text', 'ink', 'bg', 'Titles, body on app background', false],
  ['Body text', 'ink-2', 'bg', 'Onboarding body, helper text', false],
  ['Section label', 'ink-3', 'bg', 'YOUR DETAILS, MY TRIPS', false],
  ['Meta text on card', 'ink-4', 'surface', 'Card meta (members, city)', false],
  ['Placeholder', 'placeholder', 'surface', 'Input placeholder', false],
  ['Button label (gradient start)', 'on-brand', 'brand-start', 'Primary button', false],
  ['Button label (gradient end)', 'on-brand', 'brand-end', 'Primary button', false],
  ['Brand text on background', 'brand', 'bg', 'Links: Add dates, Hint, Waiting', false],
  ['Disabled button label', 'on-brand', 'brand-disabled', 'Disabled primary button', false],
  ['Chip: Voting', 'info', 'info-tint', 'Status chip', false],
  ['Chip: Ready', 'success', 'success-tint', 'Status chip', false],
  ['Chip: Draft', 'neutral', 'neutral-tint', 'Status chip', false],
  ['Text on navy header', 'on-navy', 'navy', 'Trip header, splash', false],
  ['Input border', 'border', 'surface', 'Field outline (UI component, 3:1)', false, true],
  ['Inactive page dot', 'dot', 'bg', 'Onboarding dots (UI component, 3:1)', false, true],
]

const rows = pairs.map(([label, fg, bg, usage, large, ui]) => {
  const r = ratio(c[fg], c[bg])
  const need = ui ? 3 : large ? 3 : 4.5
  const exempt = label.startsWith('Disabled')
  const status = exempt ? 'exempt (disabled)' : r >= need ? 'pass' : 'FLAG'
  return { label, fg, bg, usage, r: r.toFixed(2), need, status }
})

const flagged = rows.filter((x) => x.status === 'FLAG')
const md = `# Accessibility flags (contrast)

Generated by \`npm run contrast\` from \`design/tokens.json\`. **Flag only.** Colours are design
decisions, so nothing here has been changed. Values are approximate until figma-sync brings exact ones.

WCAG 2.2 AA: normal text 4.5:1 · large text (≥24px, or ≥18.66px bold) 3:1 · UI component outlines 3:1.

**${flagged.length} of ${rows.length} pairings flagged.**

| Pairing | Tokens | Used for | Ratio | Needs | Status |
|---|---|---|---|---|---|
${rows.map((x) => `| ${x.label} | \`${x.fg}\` on \`${x.bg}\` | ${x.usage} | ${x.r}:1 | ${x.need}:1 | ${x.status} |`).join('\n')}

## Other flags (not colour)
- Thumbs up/down buttons on voting cards render at ~28px. Apple's minimum touch target is 44×44pt, so
  the build gives them a 44px hit area without changing what they look like.
- Calendar availability must not rely on colour alone. Group calendar uses per-member dots and a
  screen-reader label per day ("12 July: John, Gabriel available").
`
writeFileSync(new URL('../design/a11y-flags.md', import.meta.url), md)
console.log(`a11y-flags.md written (${flagged.length} flagged)`)
