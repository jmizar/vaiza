// Generates src/styles/tokens.css from design/tokens.json.
// Tailwind v4 reads the @theme block, so every token becomes a utility
// (e.g. color.ink -> `text-ink`, radius.md -> `rounded-md`).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'

const t = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'))
const lines = []
const v = (name, value) => lines.push(`  --${name}: ${value};`)

for (const [k, val] of Object.entries(t.color)) v(`color-${k}`, val)
for (const [k, val] of Object.entries(t.radius)) v(`radius-${k}`, val)
for (const [k, val] of Object.entries(t.shadow)) v(`shadow-${k}`, val)
for (const [k, val] of Object.entries(t.text)) {
  v(`text-${k}`, val.size)
  v(`text-${k}--line-height`, val.line)
  v(`text-${k}--font-weight`, val.weight)
  v(`text-${k}--letter-spacing`, val.tracking)
}
v('font-sans', t.font.family)
v('spacing', '4px')

const runtime = []
const r = (name, value) => runtime.push(`  --${name}: ${value};`)
for (const [k, val] of Object.entries(t.gradient)) r(`gradient-${k}`, val)
for (const [k, val] of Object.entries(t.glass ?? {})) r(`glass-${k}`, val)
for (const [k, val] of Object.entries(t.motion)) if (typeof val === 'string') r(`motion-${k}`, val)
for (const [k, val] of Object.entries(t.size)) r(`size-${k}`, val)

const css = `/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */
@theme {
  --color-*: initial;
${lines.join('\n')}
}

:root {
${runtime.join('\n')}
}
`
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css)

// Motion values the JS side needs (springs can't live in CSS).
writeFileSync(
  new URL('../src/styles/motion.gen.ts', import.meta.url),
  `// GENERATED by scripts/build-tokens.mjs. Do not edit by hand.\nexport const motionTokens = ${JSON.stringify(t.motion, null, 2)} as const\n`,
)
console.log('tokens.css + motion.gen.ts written')
