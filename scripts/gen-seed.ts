// Writes supabase/seed.sql from the app's reference data so there is one source of truth.
// Run: npm run seed
import { writeFileSync } from 'node:fs'
import { CITIES } from '../src/data/cities.ts'
import { DESTINATIONS } from '../src/data/destinations.ts'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const arr = (xs: Array<string | number>) =>
  `'{${xs.map((x) => (typeof x === 'number' ? x : `"${x}"`)).join(',')}}'`

const cities = CITIES.map((c) => `(${q(c.id)}, ${q(c.name)}, ${q(c.countryCode)}, ${c.lat}, ${c.lon})`)
const dests = DESTINATIONS.map(
  (d) =>
    `(${q(d.id)}, ${q(d.name)}, ${q(d.country)}, ${q(d.countryCode)}, ${q(d.continent)}, ${q(d.iata)}, ${d.lat}, ${d.lon}, ${d.costPerDay}, ${arr(d.activities)}, ${arr(d.bestMonths)})`,
)

const sql = `-- GENERATED by scripts/gen-seed.ts from src/data. Do not edit by hand.
insert into public.cities (id, name, country_code, lat, lon) values
${cities.join(',\n')}
on conflict (id) do update set name = excluded.name, country_code = excluded.country_code, lat = excluded.lat, lon = excluded.lon;

insert into public.destinations (id, name, country, country_code, continent, iata, lat, lon, cost_per_day, activities, best_months) values
${dests.join(',\n')}
on conflict (id) do update set name = excluded.name, country = excluded.country, country_code = excluded.country_code,
  continent = excluded.continent, iata = excluded.iata, lat = excluded.lat, lon = excluded.lon,
  cost_per_day = excluded.cost_per_day, activities = excluded.activities, best_months = excluded.best_months;
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`seed.sql: ${CITIES.length} cities, ${DESTINATIONS.length} destinations`)
